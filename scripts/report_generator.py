import json
from pathlib import Path
from datetime import datetime

from scripts.website_quality_checks import check_website_quality


PROJECT_ROOT = Path(__file__).resolve().parent.parent

INPUT_PATH = (
    PROJECT_ROOT
    / "data"
    / "sample_leads"
    / "labeldc_analysis.json"
)

OUTPUT_DIR = PROJECT_ROOT / "reports"
OUTPUT_PATH = OUTPUT_DIR / "labeldc_business_report.md"


def generate_report(analysis):
    source = analysis["source_data"]
    validation = analysis["validated_analysis"]

    products = validation.get("accepted_products_or_services", [])
    rejected = validation.get("rejected_products_or_services", [])
    limitations = validation.get("limitations", [])

    website_data = {
        "website": source.get("website", ""),
        "title": source.get("page_title", ""),
        "meta_description": source.get("meta_description", ""),
        "headings": source.get("headings", []),
    }

    quality_result = check_website_quality(website_data)
    findings = quality_result["findings"]

    lines = [
        "# Business Website Analysis Report",
        "",
        f"**Website:** {source.get('website', 'Unknown')}",
        f"**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        f"**HTTP Status:** {source.get('http_status', 'Unknown')}",
        "",
        "## 1. Business Overview",
        "",
        validation.get("business_summary", "Not available."),
        "",
        f"**Business Type:** {validation.get('business_type', 'Not identified')}",
        "",
        "**Target Audience:**",
        validation.get("target_audience") or "Not explicitly identified.",
        "",
        "## 2. Products and Services",
        "",
    ]

    if products:
        lines.extend(f"- {item}" for item in products)
    else:
        lines.append("No supported products or services identified.")

    lines.extend([
        "",
        "## 3. Website Information",
        "",
        f"**Page Title:** {source.get('page_title', 'Not available')}",
        "",
        f"**Meta Description:** {source.get('meta_description', 'Not available')}",
        "",
        f"**Internal Links Extracted:** {len(source.get('internal_links', []))}",
        f"**External Links Extracted:** {len(source.get('external_links', []))}",
        f"**Email Candidates:** {len(source.get('emails', []))}",
        f"**Phone Candidates:** {len(source.get('phone_candidates', []))}",
        "",
        "## 4. Website Quality Checks",
        "",
        f"**Checks performed:** {quality_result['checks_performed']}",
        f"**Findings:** {quality_result['findings_count']}",
        "",
    ])

    if findings:
        for item in findings:
            lines.extend([
                f"### {item['id']} — {item['finding']}",
                f"- **Category:** {item['category']}",
                f"- **Severity:** {item['severity']}",
                f"- **Evidence:** {item['evidence']}",
                "",
            ])
    else:
        lines.append("No issues detected by the automated checks.")

    lines.extend([
        "",
        "## 5. Rejected Product or Service Claims",
        "",
    ])

    if rejected:
        for item in rejected:
            lines.append(
                f"- **{item['item']}** — {item['reason']}"
            )
    else:
        lines.append("No product or service claims were rejected.")

    lines.extend([
        "",
        "## 6. Limitations",
        "",
    ])

    if limitations:
        lines.extend(f"- {item}" for item in limitations)
    else:
        lines.append("No limitations reported by the AI.")

    lines.extend([
        "",
        "## 7. Validation Notes",
        "",
        validation.get("validation_note", "No validation notes available."),
        "",
        "## 8. Manual Review Required",
        "",
        "- Verify business information against the official website.",
        "- Review AI-generated business descriptions.",
        "- Confirm product and service claims before contacting the prospect.",
        "- Review automated website quality findings manually.",
        "- Do not treat missing extracted information as proof that it does not exist.",
        "",
        "---",
        "",
        "*Generated by the Personal AI Freelancing System.*",
    ])

    return "\n".join(lines)


def main():
    if not INPUT_PATH.exists():
        raise FileNotFoundError(
            f"Analysis file not found: {INPUT_PATH}"
        )

    with open(INPUT_PATH, "r", encoding="utf-8") as file:
        analysis = json.load(file)

    report = generate_report(analysis)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(report, encoding="utf-8")

    print(f"Report generated: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()